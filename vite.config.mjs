function createGeneratedFileHeader(source, output) {
    if (path.extname(output) === '.css') {
        return [
            `/* Generated from ${source}.`,
            ' * Do not edit this file directly. Run `npm run build` after editing the source file.',
            ' */',
            '',
        ].join('\n');
    }

    return [
        `// Generated from ${source}.`,
        '// Do not edit this file directly. Run `npm run build` after editing the source file.',
        '',
    ].join('\n');
}

function writeGeneratedScript(source, output) {
    fs.mkdirSync(path.dirname(output), {recursive: true});
    fs.writeFileSync(output, createGeneratedFileHeader(source, output) + fs.readFileSync(source, 'utf8'));
}

/**
 * Copies the hand-maintained public display / plugin assets into `public/`
 * during the Vite build. This replaces the equivalent step that used to run
 * in Laravel Mix (`webpack.mix.js`).
 */
function copyStaticAssets() {
    return {
        name: 'buku-masjid-copy-static-assets',
        apply: 'build',
        closeBundle() {
            publicDisplayScripts.forEach((fileName) => writeGeneratedScript(
                `resources/assets/js/public_display/${fileName}`,
                `public/js/public_display/${fileName}`,
            ));

            appOwnedPluginScripts.forEach((fileName) => writeGeneratedScript(
                `resources/assets/js/plugins/${fileName}`,
                `public/js/plugins/${fileName}`,
            ));

            vendorPluginScripts.forEach((fileName) => writeGeneratedScript(
                `resources/vendor/js/${fileName}`,
                `public/js/plugins/${fileName}`,
            ));

            vendorPluginStyles.forEach((fileName) => writeGeneratedScript(
                `resources/vendor/css/${fileName}`,
                `public/css/plugins/${fileName}`,
            ));
        },
    };
}

export default defineConfig({
    plugins: [
        laravel({
            input: ['resources/sass/app.scss', 'resources/js/app.js'],
        }),
        copyStaticAssets(),
    ],
    build: {
        // Windows 7 clients cannot run anything newer than Firefox 115 ESR or
        // Chrome 109, so the bundle must not rely on newer CSS APIs.
        target: ['firefox115', 'chrome109'],
    },
    css: {
        postcss: {
            plugins: [
                // The plugin emits a light fallback (the first argument) and
                // keeps the real light-dark() behind @supports, so modern
                // browsers can honor dark mode while legacy browsers stay
                // light. The preset's own light-dark fallback is disabled
                // because it emits a toggle variable that nothing in this
                // project defines.
                resolveLightDark.plugin,
                postcssPresetEnv({
                    browsers: ['firefox 115', 'chrome 109'],
                    features: {'light-dark-function': false},
                }),
            ],
        },
        preprocessorOptions: {
            scss: {
                // Vite 5 can drive Dart Sass through its modern compiler API,
                // which runs in a worker and avoids the `legacy-js-api`
                // deprecation warning entirely.
                api: 'modern-compiler',
            },
        },
    },
    base: './',
});
